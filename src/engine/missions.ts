import { makeNode, makeTree } from './treeAlgorithms';

function buildTree(structure: (string | null)[][]): BinaryTree {
  // structure: each entry is [label, leftLabel|null, rightLabel|null]
  // Build a simple tree from a flat definition
  if (structure.length === 0) return makeTree(null);

  const nodes: Record<string, ReturnType<typeof makeNode>> = {};
  for (const [label] of structure) {
    if (label) nodes[label] = makeNode(label);
  }
  for (const [label, left, right] of structure) {
    if (!label) continue;
    nodes[label].left = left ? nodes[left] : null;
    nodes[label].right = right ? nodes[right] : null;
  }
  const root = nodes[structure[0][0]!];
  return makeTree(root);
}

